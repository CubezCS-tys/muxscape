#!/usr/bin/env python3
"""Write THIRD_PARTY_LICENSES.txt for what the desktop app ships:
Rust crates compiled into the Windows app (normal dependencies only) and the
UI's production npm packages (including the bundled fonts).

Usage: python3 dev/release/third_party_licenses.py  (from the repo root)
"""
import glob, hashlib, json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "THIRD_PARTY_LICENSES.txt")
LIC_RE = re.compile(r"^(licen[cs]e|copying|notice|unlicense|copyright|authors)([-_.].*)?$", re.I)

def licence_files(d):
    try:
        names = sorted(os.listdir(d))
    except OSError:
        return []
    return [os.path.join(d, n) for n in names if LIC_RE.match(n) and os.path.isfile(os.path.join(d, n))]

def read(p):
    with open(p, encoding="utf-8", errors="replace") as f:
        return f.read().strip()

entries = []  # (ecosystem, name, version, licence, repo, [texts])

# ---- Rust: normal deps of the desktop app, for the Windows target.
meta = json.loads(subprocess.check_output(
    ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", "x86_64-pc-windows-msvc"],
    cwd=ROOT, env={**os.environ}))
pkgs = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
root = next(p["id"] for p in meta["packages"] if p["name"] == "muxscape")
seen, stack = set(), [root]
while stack:
    pid = stack.pop()
    if pid in seen:
        continue
    seen.add(pid)
    for d in nodes[pid]["deps"]:
        if any(k["kind"] is None for k in d["dep_kinds"]):  # normal deps only
            stack.append(d["pkg"])
workspace = set(meta["workspace_members"])
for pid in sorted(seen, key=lambda i: (pkgs[i]["name"], pkgs[i]["version"])):
    if pid in workspace:
        continue
    p = pkgs[pid]
    d = os.path.dirname(p["manifest_path"])
    texts = [read(f) for f in licence_files(d)]
    if p.get("license_file"):
        lf = os.path.join(d, p["license_file"])
        if os.path.isfile(lf):
            texts.append(read(lf))
    entries.append(("Rust crate", p["name"], p["version"], p.get("license") or "see licence text", p.get("repository") or "", texts))

# ---- npm: production dependencies of the UI (bundled into the app).
UI = os.path.join(ROOT, "ui")
def npm_walk(name, base, acc):
    d = os.path.join(base, "node_modules", name)
    if not os.path.isdir(d):
        d = os.path.join(UI, "node_modules", name)
    pj = os.path.join(d, "package.json")
    if not os.path.isfile(pj) or d in acc:
        return
    j = json.load(open(pj))
    acc[d] = j
    for dep in (j.get("dependencies") or {}):
        npm_walk(dep, d, acc)
acc = {}
for dep in json.load(open(os.path.join(UI, "package.json"))).get("dependencies", {}):
    npm_walk(dep, UI, acc)
for d, j in sorted(acc.items(), key=lambda kv: kv[1]["name"]):
    lic = j.get("license") or (j.get("licenses") or [{}])[0].get("type") or "see licence text"
    repo = j.get("repository")
    repo = repo.get("url", "") if isinstance(repo, dict) else (repo or "")
    entries.append(("npm package", j["name"], j.get("version", ""), lic, repo, [read(f) for f in licence_files(d)]))

# ---- Write, with each distinct licence text printed once.
texts, order = {}, []
for e in entries:
    for t in e[5]:
        h = hashlib.sha256(t.encode()).hexdigest()[:12]
        if h not in texts:
            texts[h] = t
            order.append(h)
missing = [f"{e[1]} {e[2]}" for e in entries if not e[5]]
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("Muxscape: third-party software\n" + "=" * 31 + "\n\n")
    f.write("Muxscape is MIT-licensed (see LICENSE.txt). It includes the components below,\n"
            "each under its own licence. Generated by dev/release/third_party_licenses.py.\n\n")
    f.write(f"{len(entries)} components. Licence texts follow the list, each printed once\n"
            "and referenced by [id].\n\n")
    for eco, name, ver, lic, repo, ts in entries:
        ids = ", ".join("[" + hashlib.sha256(t.encode()).hexdigest()[:12] + "]" for t in ts) or "(no licence file shipped; licence: " + lic + ")"
        f.write(f"- {name} {ver} ({eco}) - {lic}{(' - ' + repo) if repo else ''}\n    texts: {ids}\n")
    f.write("\n\n" + "=" * 78 + "\nLICENCE TEXTS\n" + "=" * 78 + "\n")
    for h in order:
        f.write(f"\n----- [{h}] " + "-" * 50 + "\n\n" + texts[h] + "\n")
print(f"{OUT}: {len(entries)} components, {len(order)} distinct texts, {os.path.getsize(OUT)//1024} KB")
if missing:
    print(f"{len(missing)} without a licence file (listed by SPDX id): " + ", ".join(missing[:15]) + (" ..." if len(missing) > 15 else ""))
